#!/usr/bin/env python3
"""
call_sheet.py — surface the leads the email pipeline structurally cannot reach.

The cold sender skips any lead without an email address, and logs it as
"Skipped - No Email Found" forever. That is currently ~64 of 157 leads: businesses
that were found, audited and verified, and then quietly dropped on the floor. Among
them are the warmest prospects in the whole list — businesses with no website at all
and a working phone, who by definition cannot be reached by email.

This writes call_sheet.md: a prioritised, deduplicated worksheet of exactly those
leads, with the verified flaw and an opening line grounded in it.

    python3 ops/call_sheet.py            # print a summary
    python3 ops/call_sheet.py --write    # write call_sheet.md

Nothing here contacts anyone. It produces a document for a human to work from.
"""
import argparse, csv, re
from collections import defaultdict
from pathlib import Path

HERE = Path(__file__).resolve().parent.parent
LEADS = HERE / "leads.csv"
SENT_LOG = HERE / "sent_log.csv"
DNC = HERE / "do_not_contact.csv"
OUT = HERE / "call_sheet.md"


def load(p):
    if not p.exists():
        return []
    with p.open(newline="", encoding="utf-8") as f:
        return list(csv.DictReader(f))


def contacted():
    """Addresses and business names we have already reached by email."""
    mails, names = set(), set()
    for r in load(SENT_LOG):
        if not (r.get("Status") or "").startswith("Sent"):
            continue
        a = (r.get("Email") or "").strip().lower()
        if a and "@" in a:
            mails.add(a)
        n = (r.get("Business Name") or "").strip().lower()
        if n:
            names.add(n)
    return mails, names


def opted_out():
    out = set()
    if DNC.exists():
        for line in DNC.read_text(encoding="utf-8").splitlines():
            a = line.split(",")[0].strip().lower()
            if a and "@" in a:
                out.add(a)
    return out


def normalise_phone(p):
    d = re.sub(r"\D", "", p or "")
    if d.startswith("44"):
        d = "0" + d[2:]
    return d


def collect():
    """Split unreachable-by-email leads into the two buckets that need different scripts."""
    mails, names = contacted()
    dnc = opted_out()
    no_site, no_email = [], []
    seen_phones = set()

    for r in load(LEADS):
        addr = (r.get("Email") or "").strip().lower()
        name = (r.get("Business Name") or "").strip()
        phone = (r.get("Phone") or "").strip()
        if addr:
            continue                       # reachable by email; the sender owns it
        if addr in dnc or name.lower() in names:
            continue                       # already contacted or opted out
        if not phone:
            continue                       # no route to them at all
        key = normalise_phone(phone)[-9:]
        if not key or key in seen_phones:
            continue                       # same number under two listings
        seen_phones.add(key)

        row = {"name": name, "trade": (r.get("Trade") or "").strip(),
               "area": (r.get("London Area") or "").strip(), "phone": phone,
               "website": (r.get("Website") or "").strip(),
               "flaw": (r.get("Biggest Flaw") or "").strip(),
               "score": (r.get("Website Score") or "").strip()}
        (no_site if (r.get("Group") or "").strip().upper() == "B" else no_email).append(row)

    for bucket in (no_site, no_email):
        bucket.sort(key=lambda x: (x["area"], x["name"]))
    return no_site, no_email


def opener_no_site(r):
    return (f"Hi, is that {r['name']}? I'm Jake, I build websites for {r['area']} "
            f"businesses. I noticed you haven't got a site — when someone searches "
            f"'{r['trade'].lower()} {r['area']}' you don't come up at all, and that "
            f"job goes to whoever does. I can put one together for a fixed one-off "
            f"price. Want me to send you a free mockup to look at first?")


def opener_no_email(r):
    flaw = r["flaw"].rstrip(".")
    if len(flaw) > 180:
        flaw = flaw[:180].rsplit(" ", 1)[0] + "…"
    return (f"Hi, is that {r['name']}? I'm Jake, I build websites for {r['area']} "
            f"businesses. I had a look at your site — {flaw[0].lower() + flaw[1:]}. "
            f"I can rebuild it for a fixed one-off price. Want me to send a free "
            f"mockup so you can see it first?")


def render(no_site, no_email):
    L = []
    L.append("# Call sheet — leads the email pipeline cannot reach\n")
    L.append("Generated by `ops/call_sheet.py`. Every business here was found, audited "
             "and verified by the lead hunter, then skipped by the sender because it "
             "has no email address. None has ever been contacted.\n")
    L.append("**Rules that still apply on the phone:** never quote a number other than "
             "**£449** one-off and **£39/mo** optional care plan; never promise Google "
             "rankings; never claim a fault you have not seen; if they say no, mark it "
             "and never call again.\n")
    L.append(f"| Bucket | Leads |\n|---|---|\n"
             f"| No website at all — warmest, call these first | {len(no_site)} |\n"
             f"| Has a website with a verified flaw, no email | {len(no_email)} |\n"
             f"| **Total** | **{len(no_site) + len(no_email)}** |\n")

    L.append("\n---\n\n## 1. No website at all — call first\n")
    L.append("They are invisible in local search. This is the strongest pitch in the "
             "whole business and none of them has been approached.\n")
    by_area = defaultdict(list)
    for r in no_site:
        by_area[r["area"] or "Unknown"].append(r)
    for area in sorted(by_area):
        L.append(f"\n### {area}\n")
        for r in by_area[area]:
            L.append(f"- [ ] **{r['name']}** — {r['trade']} — `{r['phone']}`  \n"
                     f"  _{opener_no_site(r)}_  \n"
                     f"  Outcome: ______________________\n")

    L.append("\n---\n\n## 2. Has a website, no email — call or use their contact form\n")
    L.append("The flaw shown is what the auditor actually observed on the live page. "
             "Lead with it; it is the proof you looked.\n")
    by_area = defaultdict(list)
    for r in no_email:
        by_area[r["area"] or "Unknown"].append(r)
    for area in sorted(by_area):
        L.append(f"\n### {area}\n")
        for r in by_area[area]:
            score = f" (scored {r['score']}/10)" if r["score"] else ""
            L.append(f"- [ ] **{r['name']}** — {r['trade']} — `{r['phone']}` — "
                     f"{r['website']}{score}  \n"
                     f"  Flaw: {r['flaw']}  \n"
                     f"  _{opener_no_email(r)}_  \n"
                     f"  Outcome: ______________________\n")
    return "".join(L)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--write", action="store_true", help="Write call_sheet.md")
    a = ap.parse_args()

    no_site, no_email = collect()
    print(f"No website at all, phone only : {len(no_site)}")
    print(f"Has website, no email         : {len(no_email)}")
    print(f"Total uncontacted, reachable  : {len(no_site) + len(no_email)}")

    if not a.write:
        print("\nDry run — pass --write to produce call_sheet.md")
        return
    OUT.write_text(render(no_site, no_email), encoding="utf-8")
    print(f"\nWrote {OUT.name}")


if __name__ == "__main__":
    main()
